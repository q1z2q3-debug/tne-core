def build_dataset():
    """把种子数据转成标准标注集。"""
    dataset = []
    seen = set()
    for text, vec, note in SEEDS:
        if len(vec) != 9:
            print(f"[跳过] 向量长度错: {text}")
            continue
        if text in seen:
            continue
        seen.add(text)
        dataset.append({
            "text": text,
            "vector": vec,
            "note": note,
        })
    return dataset


def save(path=None):
    # 固定保存到项目根 data/ 目录（避免相对路径歧义）
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
    path = path or os.path.join(root, "data", "teacher_seeds.json")
    dataset = build_dataset()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"meta": {"teacher": "doubao", "count": len(dataset),
                            "note": "教师模型标注的九维种子数据"},
                   "samples": dataset}, f, ensure_ascii=False, indent=2)
    # 统计
    from collections import Counter
    dims = Counter()
    for s in dataset:
        for d in range(9):
            dims[(d, s["vector"][d])] += 1
    print(f"种子数据: {len(dataset)} 条")
    print("各爻三态分布（d:阳/中/阴）:")
    for d in range(9):
        print(f"  g{d+1}: 阳{ dims[(d,1)]} 中{dims[(d,0)]} 阴{dims[(d,-1)]}")
    return path


if __name__ == "__main__":
    p = save()
    print(f"已保存: {p}")
