def main():
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
    path = os.path.join(root, "data", "teacher_seeds.json")
    data = json.load(open(path, encoding="utf-8"))
    existing = {s["text"] for s in data["samples"]}
    added = 0
    for text, vec, note in SEEDS6:
        if text in existing or len(vec) != 9:
            continue
        data["samples"].append({"text": text, "vector": vec, "note": note})
        existing.add(text)
        added += 1
    data["meta"]["count"] = len(data["samples"])
    json.dump(data, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)

    from collections import Counter
    dims = Counter()
    for s in data["samples"]:
        for d in range(9):
            dims[(d, s["vector"][d])] += 1
    print(f"新增 {added} 条 | 总 {len(data['samples'])} 条")
    for d in range(9):
        print(f"  g{d+1}: 阳{dims[(d,1)]} 中{dims[(d,0)]} 阴{dims[(d,-1)]}")

if __name__ == "__main__":
    main()
